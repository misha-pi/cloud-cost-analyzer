"""
Write viz_rill/dashboards/atlas_forecast_canvas.yaml, the MongoDB Atlas Spend Report page, with one chart per
project in the loaded Atlas data.

Rill cannot repeat a chart once per value, so the page is generated: the script counts the projects that the
page's model (models/atlas_forecast_monthly.sql) ranks, i.e. projects with Atlas cost in the 12 complete
months before the month of the latest billed day, and writes that many charts. The page file is gitignored
because it depends on the data; `make run-atlas`, `make atlas-demo-data`, `make demo` and `make serve` run
this script.

Usage:
  uv run python scripts/generate_atlas_forecast_page.py                # count projects in the Atlas data
  uv run python scripts/generate_atlas_forecast_page.py --projects 12  # write 12 project charts
"""
import argparse
import glob
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LINE_ITEMS = ROOT / "viz_rill" / "data" / "atlas_billing" / "line_items"
PAGE = ROOT / "viz_rill" / "dashboards" / "atlas_forecast_canvas.yaml"

# Same label as models/atlas_costs.sql for lines without a project (Support, ...).
NO_PROJECT = "(no project)"


def _month_index(day) -> int:
    return day.year * 12 + day.month - 1


def count_projects(line_items_dir: pathlib.Path = LINE_ITEMS) -> int:
    """
    Projects the page's model ranks: those with a line item (cost not null) in the 12 complete months before
    the month of the latest billed day, or fewer months when the data is shorter. 0 when there is no data.
    """
    files = sorted(glob.glob(str(line_items_dir / "*.parquet")))
    if not files:
        return 0
    import pyarrow.parquet as pq

    rows = []
    for path in files:
        table = pq.read_table(path, columns=["date", "project_name", "cost"])
        rows += [
            (day, project)
            for day, project, cost in zip(*(table.column(c).to_pylist() for c in ("date", "project_name", "cost")))
            if cost is not None and day is not None
        ]
    if not rows:
        return 0
    open_month = max(_month_index(day) for day, _ in rows)
    return len({project or NO_PROJECT for day, project in rows if open_month - 12 <= _month_index(day) < open_month})


HEADER = """# GENERATED by scripts/generate_atlas_forecast_page.py: do not edit (it is gitignored and rewritten after
# every Atlas load). Change the script instead.
#
# MongoDB Atlas spend report for the contract talks: monthly billed cost over the last 12 complete months,
# per project, and the next-12-month projection. Data: atlas_forecast_monthly and atlas_forecast_estimates.
# One chart per project ({projects} projects in the data when this was generated), each the same chart
# filtered to one project rank.
type: canvas
display_name: "MongoDB Atlas Spend Report and 12-Month Forecast"

defaults:
  time_range: inf
  comparison_mode: none

rows:
  - items:
      - markdown:
          content: |
            ### MongoDB Atlas spend: past 12 months (actual) and next 12 months (projection)
            MongoDB Atlas billed cost, from the Atlas line items, for the 12 complete months
            **{{{{ metrics_sql "SELECT months_used FROM atlas_forecast_estimate_metrics WHERE line_type = 'total'" }}}}**
            (the current month is still being billed and is left out). Each month adds up to its Atlas invoice.

            **How the numbers are worked out**
            - **Past 12 months (actual)** = billed cost over those 12 months.
            - **Next 12 months (projection)** = past 12 months x 1.1 (a 10% growth allowance).
            - The same rule is applied to the total and to each project. Nothing is left out as a one-off spike.
              Sales tax is billed on the invoice, not on the line items, and is $0 on our invoices.
              Org-level lines (e.g. Support) have no project and show as **(no project)**.
            - The **straight-line trend** on each chart is fitted to the monthly cost, to show whether it is rising
              or falling. It is not used for the projection.
            - Projects are ranked by their past-12-month cost, with one chart per project below the table.
        width: 12
    height: 330px

  - items:
      - kpi_grid:
          metrics_view: atlas_forecast_estimate_metrics
          title: "Total MongoDB Atlas cost"
          measures: [avg_monthly_cost, past_12m_actual, next_12m_projection]
          sparkline: none
          hide_time_range: true
          comparison: []
          dimension_filters: "line_type IN ('total')"
          hide_local_filters: true
        width: 12
    height: 130px

  - items:
{total_chart}        width: 12
    height: 360px

  - items:
      - pivot:
          metrics_view: atlas_forecast_estimate_metrics
          title: "Cost per project"
          row_dimensions: [ranked_project]
          measures: [avg_monthly_cost, past_12m_actual, next_12m_projection]
          dimension_filters: "line_type IN ('project')"
          hide_local_filters: true
        width: 12
    height: {table_height}px
"""

CHART = """      - line_chart:
          metrics_view: atlas_forecast_monthly_metrics
          title: "{title}"
{description}          dimension_filters: "rank IN ('{rank}')"
          hide_local_filters: true
          x:
            field: month_label
            type: nominal
            sort: x
          y:
            field: monthly_cost
            type: quantitative
            zeroBasedOrigin: true
          color:
            field: series
            type: nominal
            colorMapping:
              - value: "Straight-line trend"
                color: "#9ca3af"
"""

FOOTER = """
filters:
  enable: false

theme: theme
"""


def render(projects: int) -> str:
    """The page YAML with `projects` project charts, two per row."""
    total_chart = CHART.format(
        title="Total MongoDB Atlas cost per month",
        description='          description: "Billed cost of all projects, with its straight-line trend"\n',
        rank=0,
    )
    # Tall enough to show every project row without scrolling inside the table.
    table_height = max(200, 120 + 24 * projects)
    page = HEADER.format(projects=projects, total_chart=total_chart, table_height=table_height)
    if projects:
        page += "\n  # One chart per project, two per row\n"
    for first in range(1, projects + 1, 2):
        page += "  - items:\n"
        for rank in range(first, min(first + 1, projects) + 1):
            page += CHART.format(title=f"Project #{rank}: cost per month", description="", rank=rank)
            page += "        width: 6\n"
        page += "    height: 300px\n"
    return page + FOOTER


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--projects", type=int, help="number of project charts (default: count them in the data)")
    args = parser.parse_args()
    projects = count_projects() if args.projects is None else args.projects
    page = render(projects)
    if PAGE.exists() and PAGE.read_text() == page:
        print(f"Atlas forecast page is up to date ({projects} project charts)")
        return
    PAGE.write_text(page)
    print(f"Wrote {os.path.relpath(PAGE, ROOT)} with {projects} project charts")


if __name__ == "__main__":
    main()
